"""Generate the il2cpp_* exports of GameAssembly.dll.

    python gen_api.py <il2cpp_api.tsv> <il2cpp_api_map.tsv> <api_hand.c> <out api_gen.c>

il2cpp_api.tsv lists the il2cpp_* functions the exact-version Windows player binds (name, return type, parameters,
noreturn flag). For every function of that list:
  * a function defined by hand in api_hand.c (EXPORT ... il2cpp_x(...)) is skipped;
  * a function with a wrapper in the Switch binary (map status "present"), or without one but whose vm:: target has
    the same signature (map column vm_target_address), forwards to that guest address through rt_call_regs with
    AAPCS64 integer/float marshalling;
  * everything else is an explicit stub that logs once and returns 0.
Prints a summary (counts and the stub list) to stdout.
"""
import csv, re, sys

hdr, map_path, hand_path, out_path = sys.argv[1:5]
apis = [(r['name'], r['returns'], r['parameters'], r['noreturn'] == '1')
        for r in csv.DictReader(open(hdr, encoding='utf-8'), delimiter='\t')]

amap = {}
try:
    for r in csv.DictReader(open(map_path, encoding='utf-8'), delimiter='\t'):
        amap[r['name']] = r
except FileNotFoundError:
    print('WARNING: no API map at', map_path)
hand = set()
for hp in hand_path.split(','):
    hand |= set(re.findall(r'^EXPORT\s[^;{]*?\b(il2cpp_\w+)\s*\(', open(hp, encoding='utf-8').read(), re.M))

# vm targets whose signature differs from the API wrapper: never forwarded blindly (hand-written or stubbed).
NO_VM_FORWARD = {'il2cpp_domain_get_assemblies', 'il2cpp_resolve_icall', 'il2cpp_shutdown'}

INT = {'bool': 'bool', 'char': 'char', 'int': 'int32_t', 'int8_t': 'int8_t', 'uint8_t': 'uint8_t', 'int16_t': 'int16_t',
       'uint16_t': 'uint16_t', 'int32_t': 'int32_t', 'uint32_t': 'uint32_t', 'int64_t': 'int64_t', 'uint64_t': 'uint64_t',
       'size_t': 'uint64_t', 'uintptr_t': 'uint64_t', 'intptr_t': 'int64_t', 'Il2CppChar': 'uint16_t', 'long': 'int32_t',
       'unsigned': 'uint32_t', 'unsigned int': 'uint32_t', 'il2cpp_array_size_t': 'uint64_t', 'gchandle': 'uint32_t',
       'Il2CppStat': 'int32_t', 'Il2CppRuntimeUnhandledExceptionPolicy': 'int32_t', 'Il2CppGCMode': 'int32_t',
       'Il2CppProfileFlags': 'int32_t', 'Il2CppGCEvent': 'int32_t', 'Il2CppTypeEnum': 'int32_t',
       'Il2CppManagedMemorySnapshot': 'uint64_t'}
unknown_types = set()


def classify(t):
    """-> C type used in the export ('void', 'void *', an integer type, 'float', 'double')."""
    t = ' '.join(w for w in t.replace('*', ' * ').split() if w not in ('const', 'struct', 'enum'))
    if t == 'void':
        return 'void'
    if '*' in t:
        return 'void *'
    if t in ('float', 'double'):
        return t
    if t in INT:
        return INT[t]
    unknown_types.add(t)          # callback typedefs and handles: pointer sized
    return 'void *'


def split_params(p):
    p = p.strip()
    if not p or p == 'void':
        return []
    out = []
    for part in p.split(','):
        part = part.strip()
        m = re.match(r'^(.*?)(\w+)$', part)        # last identifier is the name (if the rest still has a type)
        typ = m.group(1).strip() if m and m.group(1).strip() else part
        if m and m.group(1).strip() in ('const', 'unsigned', 'struct', 'enum'):
            typ = part
        out.append(classify(typ))
    return out


def ret_expr(ct):
    if ct == 'void *':
        return '(void *)(uintptr_t)c->x[0]'
    if ct == 'bool':
        return '(c->x[0] & 0xff) != 0'
    if ct == 'float':
        return 'rt_getf(c, 0)'
    if ct == 'double':
        return 'rt_getd(c, 0)'
    return f'({ct})c->x[0]'


out = ['// GENERATED by gen_api.py - do not edit.', '#include "rt.h"', '#include "api.h"', '']
stats = dict(forward=0, vm_forward=0, stub=0, hand=0)
stubs, vm_forwards = [], []
for name, ret, params, noret in apis:
    if name in hand:
        stats['hand'] += 1
        continue
    r = amap.get(name)
    addr = None
    if r and r['status'] == 'present' and r['address']:
        addr = int(r['address'], 16)
        stats['forward'] += 1
    elif r and r.get('vm_target_address') and name not in NO_VM_FORWARD:
        addr = int(r['vm_target_address'], 16)
        stats['vm_forward'] += 1
        vm_forwards.append(name)
    rt = classify(ret)
    ps = split_params(params)
    decl = ', '.join(f'{t} a{i}' for i, t in enumerate(ps)) or 'void'
    body = [f'EXPORT {rt} {name}({decl}) {{']
    if addr is None:
        stats['stub'] += 1
        stubs.append(name)
        for i in range(len(ps)):
            body.append(f'    (void)a{i};')
        body.append(f'    static int logged; api_stub("{name}", &logged);')
        if rt != 'void':
            body.append('    return 0;')
    else:
        body.append(f'    Cpu *c = api_enter("{name}");')
        gi = fi = 0
        for i, t in enumerate(ps):
            if t == 'float':
                body.append(f'    rt_setf(c, {fi}, a{i});'); fi += 1
            elif t == 'double':
                body.append(f'    rt_setd(c, {fi}, a{i});'); fi += 1
            elif t == 'void *':
                body.append(f'    c->x[{gi}] = (uint64_t)(uintptr_t)a{i};'); gi += 1
            else:
                body.append(f'    c->x[{gi}] = (uint64_t)a{i};'); gi += 1
        assert gi <= 8 and fi <= 8, name
        body.append(f'    api_call(c, {addr:#x}, "{name}");')
        if noret:
            body.append(f'    rt_fatal_c(c, "{name} returned");')
        elif rt != 'void':
            body.append(f'    return {ret_expr(rt)};')
    body.append('}')
    out += body
out.append('typedef struct { const char *name; uint64_t addr; } ApiAddr;')
out.append('const ApiAddr api_addrs[] = {')
for name, r in amap.items():
    a = r['address'] if r['status'] == 'present' and r['address'] else r.get('vm_target_address')
    if a:
        out.append(f'    {{"{name}", {int(a, 16):#x}}},')
out.append('    {0, 0}};')
out.append('const int api_addr_count = sizeof api_addrs / sizeof api_addrs[0] - 1;')
open(out_path, 'w', newline='\n').write('\n'.join(out) + '\n')
print(f'api: {len(apis)} functions: {stats["forward"]} forward to the Switch wrapper, {stats["vm_forward"]} forward to the '
      f'vm:: target, {stats["hand"]} hand-written, {stats["stub"]} stubs')
print('vm-forwarded:', ' '.join(vm_forwards))
print('stubs:', ' '.join(stubs))
if unknown_types:
    print('pointer-sized typedefs assumed:', ' '.join(sorted(unknown_types)))
