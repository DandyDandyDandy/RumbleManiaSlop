"""Compile the generated C (build/generated, written by port/recomp/gen_il2cpp.py) to objects. Does not link.

Usage: build.py [--gen build/generated] [--out build/obj] [--jobs N] [--only-ninja] [-k]

Writes <out>/build.ninja and runs Ninja on it: every generated C file is compiled with clang (llvm-mingw) into
<out>/obj/gen/<name>.o (incremental: Ninja recompiles a file when it, a header it includes or the flags change;
the generator leaves unchanged chunks untouched). When every object exists and Ninja succeeded it writes
<out>/gen_objs.rsp (one object path per line, for the link step that the runtime's build owns) and
<out>/gen_undefined.txt (every undefined symbol the objects reference that no generated object defines, from llvm-nm).

Flags follow xc2-recomp tools/build_game.py GEN_FLAGS (MIT, Copyright (c) 2026 Peiikai).
"""
import argparse
import json
import os
import subprocess
import sys
import time
from concurrent.futures import ThreadPoolExecutor
from pathlib import Path

PORT = Path(__file__).resolve().parent
sys.path.insert(0, str(PORT))
import paths  # noqa: E402

CLANG, NINJA, NM = paths.llvm('clang'), paths.ninja(), paths.llvm('llvm-nm')
GEN_FLAGS = ['-O1', '-fno-strict-aliasing', '-Wno-return-type', '-Wno-unused-label', '-fvisibility=hidden',
             '-march=x86-64-v3']


def npath(p):
    return Path(p).as_posix().replace('$', '$$').replace(' ', '$ ').replace(':', '$:')


def cpath(p):
    s = Path(p).as_posix()
    return f'"{s}"' if ' ' in s else s


def main():
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument('--gen', type=Path, default=paths.GENERATED)
    ap.add_argument('--out', type=Path, default=paths.OBJ)
    ap.add_argument('--jobs', type=int, default=os.cpu_count() or 4)
    ap.add_argument('--only-ninja', action='store_true', help='write build.ninja and stop')
    ap.add_argument('-k', '--keep-going', action='store_true', help='keep compiling after errors (ninja -k 0)')
    args = ap.parse_args()
    gen, out = args.gen.resolve(), args.out.resolve()
    manifest = json.loads((gen / 'manifest.json').read_text())
    sources = [gen / c for c in manifest['chunks']] + [gen / s for s in manifest['extra_sources']]
    objdir = out / 'obj' / 'gen'
    objdir.mkdir(parents=True, exist_ok=True)
    objs = [objdir / (s.stem + '.o') for s in sources]
    inc = PORT / 'runtime' / 'include'
    lines = ['# Generated by port/build.py. Do not edit.', 'ninja_required_version = 1.10',
             f'builddir = {npath(out)}',
             f'cc = {cpath(CLANG)}',
             f'genflags = {" ".join(GEN_FLAGS)} -I {cpath(inc)} -I {cpath(gen)}', '',
             'rule cc_gen', '  command = $cc $genflags -MD -MF $out.d -c $in -o $out', '  deps = gcc',
             '  depfile = $out.d', '  description = CC $out', '']
    lines += [f'build {npath(o)}: cc_gen {npath(s)}' for s, o in zip(sources, objs)]
    lines += ['', 'build gen: phony ' + ' '.join(npath(o) for o in objs), 'default gen', '']
    ninja = out / 'build.ninja'
    text = '\n'.join(lines)
    if not ninja.exists() or ninja.read_text(encoding='utf-8') != text:
        ninja.write_text(text, encoding='utf-8', newline='\n')
    # Objects of chunks that no longer exist would otherwise stay around (and in nobody's list).
    keep = {o.name for o in objs}
    for p in objdir.glob('*.o'):
        if p.name not in keep:
            p.unlink()
            Path(str(p) + '.d').unlink(missing_ok=True)
    if args.only_ninja:
        return 0
    env = paths.tool_env()
    t0 = time.perf_counter()
    cmd = [str(NINJA), '-f', str(ninja), '-j', str(args.jobs)] + (['-k', '0'] if args.keep_going else [])
    r = subprocess.run(cmd, cwd=out, env=env)
    print(f'ninja: exit {r.returncode}, {time.perf_counter() - t0:.0f}s', file=sys.stderr)
    rsp = out / 'gen_objs.rsp'
    if r.returncode or not all(o.exists() for o in objs):
        rsp.unlink(missing_ok=True)
        return r.returncode or 1
    rsp.write_text(''.join(f'"{o.as_posix()}"\n' for o in objs), encoding='utf-8', newline='\n')

    def nm(group):
        return subprocess.run([str(NM), '--format=posix'] + [str(o) for o in group], capture_output=True, text=True,
                              check=True).stdout

    groups = [objs[i:i + 20] for i in range(0, len(objs), 20)]
    defined, undefined = set(), set()
    with ThreadPoolExecutor(args.jobs) as pool:
        for text in pool.map(nm, groups):
            for line in text.splitlines():
                p = line.split()
                if len(p) >= 2 and len(p[1]) == 1:
                    (undefined if p[1] == 'U' else defined).add(p[0])
    und = sorted(undefined - defined)
    (out / 'gen_undefined.txt').write_text('\n'.join(und) + '\n', encoding='utf-8', newline='\n')
    size = sum(o.stat().st_size for o in objs)
    print(f'{len(objs)} objects, {size / 1e6:.0f} MB; {len(und)} undefined symbols -> {out / "gen_undefined.txt"}',
          file=sys.stderr)
    return 0


if __name__ == '__main__':
    sys.exit(main())
